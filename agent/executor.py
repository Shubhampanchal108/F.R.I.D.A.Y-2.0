def _inject_context(params: dict, tool: str, step_results: dict, goal: str = "") -> dict:
    """
    Pipes results from earlier steps into parameters of downstream tools.
    For example: Pipes web search notes into file content or email body.
    """
    if not step_results:
        return params

    params = dict(params)

    # 0. Global template replacement for placeholders like {{step1_output}}
    for k, v in list(params.items()):
        if isinstance(v, str):
            for step_idx, step_out in step_results.items():
                out_str = str(step_out)
                placeholders = [
                    f"{{{{step{step_idx}_output}}}}",
                    f"{{{{step_{step_idx}_output}}}}",
                    f"{{{{step{step_idx}}}}}",
                    f"{{{{step_{step_idx}}}}}"
                ]
                for ph in placeholders:
                    if ph.lower() in v.lower():
                        params[k] = v.replace(ph, out_str)
                        v = params[k]

    # 1. Inject into file content
    if tool in ("create_and_open_file", "update_file"):
        content_key = "content" if tool == "create_and_open_file" else "new_content"
        curr_content = str(params.get(content_key, "")).strip()

        if len(curr_content) < 40 or any(p in curr_content.lower() for p in ["placeholder", "results from", "summary here", "content from", "step1_output"]):
            meaningful_results = [
                str(v) for v in step_results.values()
                if v and len(str(v)) > 50 and not str(v).startswith("❌") and not str(v).startswith("⚠")
            ]
            if meaningful_results:
                combined_raw = "\n\n---\n\n".join(meaningful_results)
                doc_header = f"# {goal.title() if goal else 'Agent Task Dossier'}\n\nGenerated by F.R.I.D.A.Y Autonomous Engine\n\n"
                params[content_key] = doc_header + combined_raw[:4500]
                print(f"[Friday Executor] 💉 Context injected into {tool} ({len(params[content_key])} chars)")

    # 2. Inject into email body
    elif tool == "send_email":
        body = str(params.get("body", "")).strip()
        if len(body) < 30 or "content" in body.lower():
            meaningful_results = [
                str(v) for v in step_results.values()
                if v and len(str(v)) > 50 and not str(v).startswith("❌")
            ]
            if meaningful_results:
                params["body"] = "\n\n".join(meaningful_results)[:2000]
                print(f"[Friday Executor] 💉 Context injected into send_email body")

    # 3. Inject file path or query into document reader / reviewer if missing
    elif tool in ("read_pdf_or_document", "read_file", "code_reviewer_agent"):
        path_key = "filepath" if tool == "read_pdf_or_document" else ("filename" if tool == "read_file" else "code_or_filename")
        if not params.get(path_key):
            for res in step_results.values():
                if isinstance(res, dict) and "filename" in res:
                    params[path_key] = res["filename"]
                    break

    return params


def _verify_step_result(step: dict, result: Any, params: dict) -> tuple[bool, str]:
    """
    Rigorously verifies if the step was genuinely successful.
    Returns (is_valid, error_explanation).
    """
    if result is None:
        return False, "Tool returned None"

    if isinstance(result, str):
        res_str = result.strip()
        if res_str.startswith("❌") or res_str.startswith("🚫") or res_str.startswith("⚠️"):
            return False, res_str
        if "error:" in res_str.lower() or "exception:" in res_str.lower():
            return False, res_str

    if isinstance(result, dict):
        if result.get("status") == "error":
            return False, result.get("message") or result.get("error") or "Step returned error status"

    tool = step.get("tool", "")
    v_type = step.get("verification_type", "status_ok")

    if v_type == "content" or tool in ("google_search", "extract_webpage_content", "deep_research_agent"):
        res_text = str(result).strip()
        if len(res_text) < 15 or "no results found" in res_text.lower():
            return False, "Search or extraction produced no actionable content"

    elif v_type == "file_exists" or tool in ("create_and_open_file",):
        filename = params.get("filename", "")
        if filename:
            from utils.paths import DOCS_PATH
            candidates = [
                filename,
                os.path.join(DOCS_PATH, filename),
                os.path.join(os.path.expanduser("~"), "Desktop", filename),
            ]
            found = any(os.path.exists(c) for c in candidates)
            if not found and not ("created" in str(result).lower() or "success" in str(result).lower()):
                return False, f"File verification failed: '{filename}' not found on disk"

    return True, ""


def _synthesize_dynamic_response(goal: str, completed_steps: list, step_results: dict, error: str = "") -> str:
    """
    Uses the LLM to dynamically formulate what to tell the user based on outcome.
    Zero hardcoded speech. The LLM decides phrasing, language, and details.
    """
    try:
        steps_summary = "\n".join([
            f"- {s.get('description', s.get('tool'))}: {str(step_results.get(s.get('step'), 'Done'))[:120]}"
            for s in completed_steps
        ]) if completed_steps else "No steps were executed."

        prompt = f"""You are F.R.I.D.A.Y 2.0, Shubham sir's AI Super-Agent and personal secretary.
User's Objective: "{goal}"

Steps Executed & Outcomes:
{steps_summary}
{"Obstacle or Error: " + error if error else ""}

Task:
Formulate your natural response to Shubham sir.
- If task succeeded: explain findings, file names, or accomplishments concisely and politely.
- If an obstacle occurred: explain what happened and suggest or take an alternative.
- STRICT RULE: Speak naturally as the AI. Do NOT output robotic templates. Output ONLY the response."""

        messages = [{"role": "user", "content": prompt}]
        response = chat_complete(messages=messages, temperature=0.3, timeout=15.0)
        
        # Guard against raw tool call JSON leaking from LLM synthesis
        tc = parse_tool_call(response)
        if tc:
            args = tc.get("args", {})
            return str(args.get("body") or args.get("message") or f"I have executed the requested task for you, sir.")
            
        return response.strip()

    except Exception:
        if error:
            return f"I encountered an obstacle while processing your request: {error}"
        return f"Completed your request regarding '{goal[:50]}'."


class FridayAgentExecutor:
    """
    Autonomous Master Agent Controller:
    - Single point of entry for user requests.
    - Understands, plans, delegates execution to Brain, verifies, and dynamically responds.
    - Zero hardcoded speech.
    """

    MAX_REPLAN_CYCLES = 3
    MAX_STEP_ATTEMPTS = 2

    def execute(
        self,
        goal: str,
        context: str = "",
        speak: Callable | None = None,
        tool_callback: Callable | None = None,
        cancel_flag: threading.Event | None = None,
        origin: str = "server"
    ) -> str:
        """
        Executes a user directive through intelligent planning and verified execution.
        """
        print(f"\n[Friday Agent Master] 🎯 Processing Directive: '{goal}'")

        # 1. Plan directive
        plan = create_plan(goal, context=context)

        # 2. Check if purely conversational or direct single/multi tool deliberation
        if plan.get("is_conversational", False) or not plan.get("steps"):
            messages = build_system_messages(goal)
            messages.append({"role": "user", "content": goal})

            conversational_reply = ""
            for _turn in range(3):
                conversational_reply = chat_complete(messages=messages, temperature=0.3, timeout=25.0)
                tool_call = parse_tool_call(conversational_reply)

                if not tool_call:
                    # Pure natural speech reply without any tool call
                    break

                tool_name = tool_call.get("tool")
                tool_args = tool_call.get("args", {})
                if not isinstance(tool_args, dict):
                    tool_args = {}

                print(f"[Friday Agent Master] ⚡ Direct Tool Detected: '{tool_name}' ({tool_args})")
                if tool_callback:
                    try:
                        tool_callback(tool_name, tool_args)
                    except Exception:
                        pass

                tool_outcome = _execute_step_via_brain(tool=tool_name, params=tool_args, origin=origin)
                raw_res = tool_outcome.get("result") if tool_outcome.get("status") == "success" else tool_outcome.get("error", "Action failed")
                print(f"[Friday Agent Master] ✔ Tool '{tool_name}' Output: {str(raw_res)[:120]}")

                # Provide tool output back to LLM to produce a natural polite response
                messages.append({"role": "assistant", "content": conversational_reply})
                messages.append({
                    "role": "user",
                    "content": (
                        f"[TOOL RESULT FOR '{tool_name}']:\n{str(raw_res)[:3000]}\n\n"
                        f"Instructions: Explain this outcome clearly, politely, and concisely to Shubham sir in natural language. "
                        f"STRICT RULE: Do NOT output raw JSON or code tags. Speak naturally as his AI secretary."
                    )
                })

            # If for any reason raw JSON remains, synthesize a dynamic response
            if parse_tool_call(conversational_reply):
                conversational_reply = _synthesize_dynamic_response(
                    goal=goal,
                    completed_steps=[{"tool": "assistant_action", "description": goal}],
                    step_results={1: "Action completed successfully"}
                )

            if speak and conversational_reply:
                try:
                    clean_text = conversational_reply.replace("*", "").replace("`", "")
                    speak(clean_text, priority=1, allow_interrupt=True, block=False)
                except Exception:
                    pass
            return conversational_reply

        completed_steps = []
        step_results = {}
        replan_cycles = 0

        while True:
            steps = plan.get("steps", [])
            if not steps:
                response = _synthesize_dynamic_response(goal, completed_steps, step_results, error="Unable to construct a viable execution plan.")
                if speak:
                    speak(response, priority=1, block=False)
                return response

            success = True
            failed_step = None
            failed_error = ""

            for step in steps:
                if cancel_flag and cancel_flag.is_set():
                    cancel_msg = "Task execution was cancelled."
                    if speak:
                        speak(cancel_msg, block=False)
                    return cancel_msg

                step_num = step.get("step", len(completed_steps) + 1)
                tool = step.get("tool")
                desc = step.get("description", "Executing step")
                raw_params = step.get("parameters", {})

                # Pipe context from earlier steps into current parameters
                params = _inject_context(raw_params, tool, step_results, goal=goal)

                print(f"\n[Friday Agent Master] ▶️ Step {step_num}: [{tool}] {desc}")

                # Update UI Ticker visually (zero audio chatter)
                if tool_callback:
                    try:
                        tool_callback(tool, {"step": step_num, "action": desc})
                    except Exception:
                        pass

                attempt = 1
                step_success = False

                while attempt <= self.MAX_STEP_ATTEMPTS:
                    if cancel_flag and cancel_flag.is_set():
                        break

                    # Delegate atomic tool execution to Brain (Worker/Slave)
                    brain_response = _execute_step_via_brain(tool, params, origin=origin)

                    if brain_response.get("status") == "error":
                        err_text = brain_response.get("error", "Execution failed")
                        print(f"[Friday Agent Master] ⚠️ Step {step_num} Attempt {attempt} failed in Brain: {err_text}")

                        diag = analyze_error(step, err_text, attempt=attempt, max_attempts=self.MAX_STEP_ATTEMPTS)
                        decision = diag.get("decision", ErrorDecision.REPLAN)

                        if decision == ErrorDecision.RETRY and attempt < self.MAX_STEP_ATTEMPTS:
                            params = generate_fix(step, err_text, attempt)
                            time.sleep(1.0)
                            attempt += 1
                            continue

                        elif decision == ErrorDecision.SKIP:
                            print(f"[Friday Agent Master] ⏩ Skipping non-critical step {step_num}")
                            step_results[step_num] = f"Skipped: {err_text}"
                            step_success = True
                            break

                        else:
                            success = False
                            failed_step = step
                            failed_error = err_text
                            break

                    result = brain_response.get("result")

                    # Verify step outcome
                    is_valid, v_err = _verify_step_result(step, result, params)
                    if not is_valid:
                        print(f"[Friday Agent Master] ⚠️ Step {step_num} verification failed: {v_err}")
                        diag = analyze_error(step, v_err, attempt=attempt, max_attempts=self.MAX_STEP_ATTEMPTS)
                        decision = diag.get("decision", ErrorDecision.REPLAN)

                        if decision == ErrorDecision.RETRY and attempt < self.MAX_STEP_ATTEMPTS:
                            params = generate_fix(step, v_err, attempt)
                            time.sleep(1.0)
                            attempt += 1
                            continue
                        else:
                            success = False
                            failed_step = step
                            failed_error = v_err
                            break

                    # Step passed and verified
                    step_results[step_num] = result
                    completed_steps.append(step)
                    step_success = True
                    print(f"[Friday Agent Master] ✅ Step {step_num} completed and verified.")
                    break

                if not step_success:
                    success = False
                    break

            if success:
                print(f"\n[Friday Agent Master] 🏆 All steps executed successfully. Synthesizing response via LLM...")
                final_response = _synthesize_dynamic_response(goal, completed_steps, step_results)
                if speak and final_response:
                    try:
                        clean_text = final_response.replace("*", "").replace("`", "")
                        speak(clean_text, priority=1, allow_interrupt=True, block=False)
                    except Exception:
                        pass
                return final_response

            # Restructure / Replan
            replan_cycles += 1
            if replan_cycles <= self.MAX_REPLAN_CYCLES:
                print(f"\n[Friday Agent Master] 🔄 Replanning remaining steps (Cycle {replan_cycles}/{self.MAX_REPLAN_CYCLES})...")
                plan = replan(goal, completed_steps, failed_step, failed_error)
            else:
                fail_response = _synthesize_dynamic_response(goal, completed_steps, step_results, error=failed_error)
                if speak and fail_response:
                    speak(fail_response, priority=1, block=False)
                return fail_response


def execute_goal(goal: str, **kwargs) -> str:
    """Helper to launch master execution."""
    executor = FridayAgentExecutor()
    return executor.execute(goal, **kwargs)
